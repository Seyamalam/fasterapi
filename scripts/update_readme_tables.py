#!/usr/bin/env python3
"""Regenerate the README parity + benchmark tables.

Usage:
    python scripts/update_readme_tables.py        # refresh in place
    python scripts/update_readme_tables.py --check  # exit 1 when stale

Refreshes the blocks between the PARITY/BENCH markers in README.md:
  * parity  — runs the pytest suites, records passed/total per file,
  * micro   — runs the in-process Rust fast-path checks (no servers),
  * macro   — reads benchmark-results/differential-latest.json when a full
    differential load has been run before this commit.

The pre-commit hook runs this (fast: ~4s) and stages README.md, so every
commit — and therefore every push — carries fresh tables. Skips gracefully
(exit 0, README untouched) when test dependencies are not installed.
Exits 1 when the suites run but parity is red (parity is king: fix first).
"""

from __future__ import annotations

import ast
import importlib.util
import json
import os
import re
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
MACRO_JSON = ROOT / "benchmark-results" / "differential-latest.json"
PARITY_FILES = ["tests/test_parity.py", "tests/test_fasterapi_native.py", "tests/test_parity_security.py"]

PARITY_START = "<!-- PARITY:START -->"
PARITY_END = "<!-- PARITY:END -->"
BENCH_START = "<!-- BENCH:START -->"
BENCH_END = "<!-- BENCH:END -->"


def _env() -> dict[str, str]:
    env = dict(os.environ)
    env["PYTHONPATH"] = str(ROOT / "python") + os.pathsep + env.get("PYTHONPATH", "")
    return env


def _have_deps() -> bool:
    try:
        subprocess.run(
            [sys.executable, "-c", "import fasterapi, pytest"],
            cwd=ROOT, env=_env(), capture_output=True, check=True,
        )
        return True
    except Exception:
        return False


def _count_tests(path: Path) -> int:
    tree = ast.parse(path.read_text())
    return sum(isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name.startswith("test_")
               for n in ast.walk(tree))


def _run_pytest() -> tuple[int, int]:
    """Returns (passed, failed) for the full suite."""
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "tests/", "-q", "--tb=no", "-p", "no:warnings"],
        cwd=ROOT, env=_env(), capture_output=True, text=True,
    )
    out = proc.stdout + proc.stderr
    passed = failed = 0
    m = re.search(r"(\d+) passed", out)
    if m:
        passed = int(m.group(1))
    m = re.search(r"(\d+) failed", out)
    if m:
        failed = int(m.group(1))
    return passed, failed


def _load_micro() -> dict:
    spec = importlib.util.spec_from_file_location(
        "bench_diff", ROOT / "benchmarks" / "benchmark_differential.py"
    )
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(ROOT / "python"))
    try:
        spec.loader.exec_module(mod)  # type: ignore[union-attr]
    finally:
        sys.path.remove(str(ROOT / "python"))
    return mod.micro_benchmarks()


def _has_rust() -> bool:
    sys.path.insert(0, str(ROOT / "python"))
    try:
        from fasterapi import _rust_bridge as b  # type: ignore

        return bool(b.HAS_RUST)
    except Exception:
        return False
    finally:
        sys.path.remove(str(ROOT / "python"))


def _read_macro() -> dict | None:
    if not MACRO_JSON.exists():
        return None
    try:
        return json.loads(MACRO_JSON.read_text())
    except Exception:
        return None


def _mb(b: int) -> str:
    return f"{b / 1e6:.1f}MB"


def render_parity(passed: int, failed: int) -> str:
    totals = {f: _count_tests(ROOT / f) for f in PARITY_FILES}
    total = sum(totals.values())
    # Attribute failures to files proportionally is guesswork; instead show the
    # honest totals: per-file collected counts + suite-wide passed/failed.
    rows = [
        f"| Differential (`tests/test_parity.py`, FastAPI vs fasterapi) | {totals[PARITY_FILES[0]]} | "
        + ("all passing" if failed == 0 else f"see run ({failed} failing)") + " |",
        f"| Auth/background/encoders (`tests/test_parity_security.py`) | {totals[PARITY_FILES[2]]} | "
        + ("all passing" if failed == 0 else f"see run ({failed} failing)") + " |",
        f"| Native (`tests/test_fasterapi_native.py`) | {totals[PARITY_FILES[1]]} | "
        + ("all passing" if failed == 0 else f"see run ({failed} failing)") + " |",
        f"| **Total** | **{total}** | **{passed} passed{f', {failed} failed' if failed else ''}** |",
    ]
    return "\n".join([
        PARITY_START,
        "> Auto-generated by `scripts/update_readme_tables.py` — do not edit by hand.",
        "",
        "| Suite | Tests | Result |",
        "|---|---|---|",
        *rows,
        "",
        "Coverage: ping, path/query/header/cookie params, validation shapes "
        "(422 `loc`/`type`/`ctx`, multi-error, malformed-JSON `json_invalid`), "
        "JSON body + `response_model`, Form, file upload, DI order + `yield` "
        "teardown, `HTTPException`, custom handlers, router prefixes, OpenAPI "
        "shapes, websockets, guards, DAG, Rust bridge, OAuth2/HTTP/API-key "
        "schemes, `Security`, password-grant forms, background tasks, "
        "datetime/UUID/Enum encoding.",
        PARITY_END,
    ])


def render_bench(micro: dict, macro: dict | None, has_rust: bool) -> str:
    lines = [
        BENCH_START,
        "> Auto-generated by `scripts/update_readme_tables.py` — do not edit by hand. "
        f"Engine: `{'Rust ext' if has_rust else 'pure-Python fallback'}`.",
        "",
        "Micro fast-paths (in-process, no servers):",
        "",
        "| Check | Baseline | fasterapi | Speedup |",
        "|---|---|---|---|",
        f"| JSON `loads` | {micro['json_std_load_s']}s stdlib | {micro['json_fast_load_s']}s SIMD | x{micro['json_loads_speedup']} |",
        f"| JSON `dumps` | stdlib | Rust bridge | x{micro['json_dumps_speedup']} |",
        f"| Model validate (`loads`+`validate_python` vs `validate_json`) | "
        f"{micro['model_classic_s']}s | {micro['model_validate_json_s']}s | x{micro['model_validate_speedup']} |",
        f"| Model dump (`dump_python`+`dumps` vs `dump_json`) | "
        f"{micro['model_classic_dump_s']}s | {micro['model_dump_json_s']}s | x{micro['model_dump_speedup']} |",
    ]
    if has_rust:
        lines.append(
            f"| Router match | {micro['router_py_s']}s Python | {micro['router_rs_s']}s `matchit` "
            f"| x{micro['router_match_speedup']} |"
        )
    else:
        lines.append("| Router match | Python fallback | (compile ext for `matchit`) | — |")
    lines += ["", "Macro load (loopback, httpx concurrency; last full run):", ""]
    if macro and macro.get("macro"):
        m = macro["macro"]
        a = m.get("fastapi+uvicorn", {})
        b = m.get("fasterapi", {})
        try:
            mtime = datetime.fromtimestamp(MACRO_JSON.stat().st_mtime, tz=timezone.utc).strftime("%Y-%m-%d")
        except Exception:
            mtime = "unknown date"
        lines += [
            f"Run: `{mtime}`, speedup **x{macro.get('speedup_rps', '?')}** "
            f"(pre-push gate defaults to x1.0; strict 3x via `FASTERAPI_MIN_SPEEDUP=3.0`).",
            "",
            "| Server | RPS | p50 | p90 | p99 | RSS |",
            "|---|---|---|---|---|---|",
            f"| fastapi+uvicorn | {a.get('rps', '?')} | {a.get('p50_ms', '?')}ms | "
            f"{a.get('p90_ms', '?')}ms | {a.get('p99_ms', '?')}ms | {_mb(a.get('rss_bytes', 0))} |",
            f"| fasterapi | {b.get('rps', '?')} | {b.get('p50_ms', '?')}ms | "
            f"{b.get('p90_ms', '?')}ms | {b.get('p99_ms', '?')}ms | {_mb(b.get('rss_bytes', 0))} |",
        ]
        pa = m.get("fastapi+uvicorn (POST /items)")
        pb = m.get("fasterapi (POST /items)")
        if pa and pb:
            lines += [
                "",
                f"POST /items (Pydantic validation path): fastapi+uvicorn {pa.get('rps', '?')} RPS vs "
                f"fasterapi {pb.get('rps', '?')} RPS → **x{macro.get('post_speedup_rps', '?')}**.",
            ]
    else:
        lines.append("No full run yet — `python benchmarks/benchmark_differential.py --quick` "
                     "writes `benchmark-results/differential-latest.json`, then re-run this script.")
    lines.append(BENCH_END)
    return "\n".join(lines)


def _replace_block(text: str, start: str, end: str, new_block: str) -> str:
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f"markers {start}..{end} not found in README.md")
    return pattern.sub(lambda _: new_block, text, count=1)


def main() -> int:
    check_only = "--check" in sys.argv
    if not _have_deps():
        print("update_readme_tables: test deps missing — skipping (run scripts/quickstart.sh).")
        return 0
    t0 = time.time()
    passed, failed = _run_pytest()
    micro = _load_micro()
    macro = _read_macro()
    has_rust = _has_rust()
    text = README.read_text()
    text = _replace_block(text, PARITY_START, PARITY_END, render_parity(passed, failed))
    text = _replace_block(text, BENCH_START, BENCH_END, render_bench(micro, macro, has_rust))
    if text != README.read_text():
        if check_only:
            print("update_readme_tables: README tables stale.")
            return 1
        README.write_text(text)
        print(f"update_readme_tables: refreshed (pytest {passed} passed"
              + (f", {failed} failed" if failed else "")
              + f", {time.time() - t0:.1f}s).")
    else:
        print("update_readme_tables: tables already fresh.")
    # Parity is king: red suites must block the commit/push, never slip through.
    if failed:
        print(f"update_readme_tables: PARITY RED ({failed} failing) — fix before committing.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
